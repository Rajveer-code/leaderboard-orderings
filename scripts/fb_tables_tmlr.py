"""Generate the manuscript's tables from committed results. No number is typed here.

Run: python scripts/fb_tables_tmlr.py
Out: manuscript/tmlr/tables.tex, shared_table.tex, sensitivity_table.tex, framework_table.tex
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "flipbudget"
OUT = ROOT / "manuscript" / "tmlr" / "tables.tex"
SENS_OUT = ROOT / "manuscript" / "tmlr" / "sensitivity_table.tex"
SHARED_OUT = ROOT / "manuscript" / "tmlr" / "shared_table.tex"
NAMES = {"111": "all three credit", "000": "none credits"}
VERIFIER_ORDER = ("2024", "boxed", "Math-Verify")  # the order of the verdict string


def cell_name(c):
    """Plain-language reading of a verdict string, e.g. 101 -> "only 2024 and Math-Verify credit"."""
    if c in NAMES:
        return NAMES[c]
    who = [v for v, bit in zip(VERIFIER_ORDER, c) if bit == "1"]
    return f"only {who[0]} credits" if len(who) == 1 else f"only {who[0]} and {who[1]} credit"
# (key in certify_results K3.sensitivity, row label, what the row changes relative to the primary)
SENS_ROWS = [  # (key in certify_results K3.sensitivity, row label)
    ("clopper_pearson", "Clopper--Pearson interval$^{a}$"),
    ("mv_reference", "Math-Verify equivalence$^{b}$"),
    ("indeterminate_dropped", "indeterminates dropped$^{c}$"),
    ("string_semantics", "string semantics$^{d}$"),
    ("models17", "seventeen-model subset$^{e}$"),
]


def thousands(n):
    return f"{n:,}".replace(",", "{,}")


def main():
    cert = json.load(open(RES / "certify_results.json", encoding="utf-8"))
    amap = json.load(open(RES / "audit_k3_map.json", encoding="utf-8"))
    cfg = json.load(open(RES / "verifier_config.json", encoding="utf-8"))
    cells = amap["census_cells"]["k3_sympy"]["27"]
    audit = amap["audit_cells"]["27|k3_sympy|sympy|as_incorrect"]
    rows = []
    for c in sorted(cells, key=lambda c: -cells[c]):
        a = audit.get(c)
        lab = cell_name(c)
        got = f"{a['x_correct']}/{a['n']}" if a and a["n"] else "--"
        rows.append(f"{c} & {lab} & {thousands(cells[c])} & {got} \\\\")
    v = cfg["verifiers"]
    shared = [
        ("answer extraction", "sentence pattern", "last boxed expression", "LaTeX and expression parse"),
        ("normalisation", "harness routine", "harness routine", "latex2sympy2"),
        ("equivalence", "sympy", "string, then sympy", "Math-Verify"),
        ("gold answer", "dataset field", "dataset field", "parsed from the solution"),
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{The eight cells on MATH-Hard. A cell is the "
                "string of the three verifiers' verdicts in the order 2024 verifier, boxed verifier, "
                "Math-Verify; $1$ is credit. The first two rows are the concordant cells, where all three "
                "verifiers agree, and only they enter the certification. The last column gives, for the "
                "400-item audit, how many audited responses in the cell have reader verdict $1$, out of how "
                "many were audited.}\n"
                "\\label{tab:cells}\n")
        f.write("\\begin{tabular}{llrr}\n\\toprule\ncell & verdicts & responses & reader verdict $1$ \\\\\n"
                "\\midrule\n")
        f.write("\n".join(rows))
        f.write("\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    with open(SHARED_OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{What the three verifiers share and where they "
                "differ. All three rest on the same symbolic algebra library, and the 2024 and boxed "
                "verifiers also share the harness's normalisation and the dataset's gold-answer field. Their "
                "agreement is informative because their extraction rules and parsers differ, not because "
                "they are independent.}\n\\label{tab:shared}\n")
        f.write("\\begin{tabular}{llll}\n\\toprule\nstep & 2024 verifier & boxed verifier & Math-Verify \\\\\n"
                "\\midrule\n")
        for r in shared:
            f.write(" & ".join(r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    k3, sens = cert["K3"], cert["K3"]["sensitivity"]
    eps0 = cert["config"]["eps0_preregistered"]

    def pooled(d, cell):
        a = d.get(cell)
        return f"{a['x_correct']}/{a['n']}" if a and a["n"] else "--"

    def curve(eps):
        return next(r for r in k3["eps_curve"] if r["eps"] == eps)

    fixed = k3["fixed_board"]
    srows = ["primary analysis & {} & {} & {} & {} & {} & {} \\\\".format(
        pooled(k3["inputs"]["audit_pooled"], "111"), pooled(k3["inputs"]["audit_pooled"], "000"),
        fixed["certified_eps0"], fixed["certified_eps_preregistered"],
        curve(0.0)["combined"], curve(eps0)["combined"])]
    for key, label in SENS_ROWS:
        s = sens[key]
        srows.append("{} & {} & {} & {} & {} & {} & {} \\\\".format(
            label, pooled(s["audit_pooled"], "111"), pooled(s["audit_pooled"], "000"),
            s["fixed_board"][0], s["fixed_board"][1], s["combined_eps0"][0], s["combined_eps0"][1]))
    with open(SENS_OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{Sensitivity analyses. Each row "
                "re-runs the whole pipeline with one element of the analysis replaced, and reports the "
                "pooled audit counts it produces in the two concordant cells together with the certified "
                "orderings, first for the primary target (all orderings at once) and then for the secondary "
                "target (one ordering at a time). "
                "$^{a}$The pooled interval, in place of Lemma~\\ref{lem:kl}. "
                "$^{b}$The routine that decides $Y^*$. "
                "$^{c}$\\textsc{none} and \\textsc{contradictory} excluded rather than scored incorrect. "
                "$^{d}$Changes the boxed verifier \\emph{and} the equivalence routine, so cells move too. "
                "$^{e}$A different set of models: its counts are out of a smaller family and are not "
                "comparable down the column.}\n"
                "\\label{tab:sensitivity}\n\\small\n")
        f.write("\\begin{tabular}{lccrrrr}\n\\toprule\n"
                "& & & \\multicolumn{2}{c}{primary target} & \\multicolumn{2}{c}{secondary target} \\\\\n"
                "\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n"
                "analysis & $111$ & $000$ & $\\varepsilon=0$ & $\\varepsilon=\\EpsPrereg$ & "
                "$\\varepsilon=0$ & $\\varepsilon=\\EpsPrereg$ \\\\\n\\midrule\n")
        f.write("\n".join(srows))
        f.write("\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print("wrote", OUT, "| cells:", len(rows), "| verifier keys:", list(v))
    print("wrote", SENS_OUT, "|", len(srows), "sensitivity rows")
    framework_table()
    registered_audit_table()


REG_OUT = ROOT / "manuscript" / "tmlr" / "registered_audit_table.tex"


def registered_audit_table():
    """Section 5.5's table: certified orderings before and after the registered labels, under the
    registered gate and with extraction-only exclusions restored (D8), and the screen's rows.
    Written only once labels exist; before then any stale copy is removed, so nothing can cite it."""
    cert = json.load(open(RES / "certify_results.json", encoding="utf-8"))
    k3, eps0 = cert["K3"], cert["config"]["eps0_preregistered"]
    if "with_v3" not in k3 and "census" not in k3:
        REG_OUT.unlink(missing_ok=True)
        return

    def comb(curve):
        return {p["eps"]: p["combined"] for p in curve}[eps0]

    rows = [("400-item audit alone", k3["fixed_board"]["certified_eps0"],
             k3["fixed_board"]["certified_eps_preregistered"], comb(k3["eps_curve"]))]
    if "with_v3" in k3:
        w = k3["with_v3"]
        rows.append(("+ registered audit", w["fixed_board"]["certified_eps0"],
                     w["fixed_board"]["certified_eps_preregistered"], comb(w["eps_curve"])))
        if "d8_extraction_restored" in w:
            d = w["d8_extraction_restored"]
            rows.append(("+ registered audit, D8$^{a}$", d["fixed_board"]["certified_eps0"],
                         d["fixed_board"]["certified_eps_preregistered"], d["combined_eps0_prereg"][1]))
    if "census" in k3:
        for tag, label in (("gate", "+ census"), ("d8_extraction_restored", "+ census, D8$^{a}$")):
            c = k3["census"][f"{tag}|sympy|as_incorrect"]
            rows.append((label, c["fixed_board"]["certified_eps0"], c["fixed_board"]["certified_eps_preregistered"],
                         comb(c["generalising_eps_curve"])))
    v3_path = RES / "audit_v3_labels.json"
    screen = json.load(open(v3_path, encoding="utf-8"))["falsification"]["sympy"]["rows"] if v3_path.exists() else []
    with open(REG_OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{Certified orderings before and after the registered "
                "labels. Primary: these items, all orderings at once; secondary: one ordering at a time. "
                "$^{a}$Batches excluded only by the extraction check restored (decision D8); every other row "
                "uses only batches that passed the registered gate. The projected census count was "
                "\\CensusProjectedMedian{} (\\CensusProjectedLow{} to \\CensusProjectedHigh{}).}\n"
                "\\label{tab:registered}\n\\small\n")
        f.write("\\begin{tabular}{lrrr}\n\\toprule\n& \\multicolumn{2}{c}{primary} & secondary \\\\\n"
                "\\cmidrule(lr){2-3}\\cmidrule(lr){4-4}\nlabels & $\\varepsilon=0$ & $\\varepsilon=\\EpsPrereg$ & "
                "$\\varepsilon=\\EpsPrereg$ \\\\\n\\midrule\n")
        for label, a, b, c in rows:
            f.write(f"{label} & {a} & {b} & {c} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
        if screen:
            f.write("\n\\medskip\n\\begin{tabular}{llrrrrl}\n\\toprule\n"
                    "screened model & cell & errors & model LB & pooled UB & margin & reject \\\\\n\\midrule\n")
            for r in screen:
                f.write(f"{r['model'].split('/')[-1]} & {r['cell']} & {r['errors']}/{r['n']} & {r['lb_model']:.3f} & "
                        f"{r['ub_pooled']:.3f} & {r['margin']:+.3f} & {'yes' if r['reject'] else 'no'} \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")
        f.write("\\end{table}\n")
    print("wrote", REG_OUT)


def framework_table():
    """T28: the framework census as a table, with commits and the validation that exists."""
    hc = ROOT / "results" / "harness_census"
    prev = {r[0]: r for r in json.load(open(hc / "prevalence.json", encoding="utf-8"))["rows"]}
    lt = json.load(open(hc / "census_lighteval.json", encoding="utf-8"))
    se = json.load(open(hc / "simple_evals_census.json", encoding="utf-8"))
    val = json.load(open(hc / "census_validation.json", encoding="utf-8"))
    ver = json.load(open(hc / "framework_versions.json", encoding="utf-8"))
    vs = val["summary"] if isinstance(val.get("summary"), dict) else {}
    lm_valid = (f"{vs.get('vulnerable', {}).get('n_agreeing_with_census', '')}/"
                f"{vs.get('vulnerable', {}).get('n_testable', '')} and "
                f"{vs.get('control', {}).get('not_vulnerable', '')}/{vs.get('control', {}).get('n_sampled', '')}"
                if vs else "yes")
    rows = [("lm-evaluation-harness", ver["lm-evaluation-harness"]["commit"] + "$^{a}$", "tasks",
             prev["lm-evaluation-harness"][1], prev["lm-evaluation-harness"][2], prev["lm-evaluation-harness"][3],
             lm_valid),
            ("OpenCompass", ver["OpenCompass"]["commit"], "configurations", prev["OpenCompass"][1],
             prev["OpenCompass"][2], prev["OpenCompass"][3], "no"),
            ("lighteval", ver["lighteval"]["commit"], "metrics", lt["n_generative"], lt["n_vulnerable"],
             round(100 * lt["n_vulnerable"] / lt["n_generative"], 1), "no"),
            ("simple-evals", ver["simple-evals"]["commit"], "string-matching modules", se["n_string_match_modules"],
             se["n_vulnerable"], round(100 * se["n_vulnerable"] / se["n_string_match_modules"], 1), "no")]
    with open(ROOT / "manuscript" / "tmlr" / "framework_table.tex", "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{Scoring configurations that record a failure to "
                "extract an answer as an incorrect answer, in four evaluation frameworks at fixed versions. "
                "Denominators are different kinds of unit and are not estimates of one common population of "
                "tasks. The last column gives, where it was run, the share of sampled units whose behaviour "
                "matched their classification, for flagged units and for controls. "
                "$^{a}$The version used for the behavioural check; the version used for the classification "
                "was not recorded.}\n"
                "\\label{tab:frameworks}\n\\small\n\\setlength{\\tabcolsep}{3pt}\n")
        f.write("\\begin{tabular}{llrrrl}\n\\toprule\nframework & version & units & flagged & \\% & "
                "validated \\\\\n\\midrule\n")
        for name, commit, unit, n, k, p, valid in rows:
            f.write(f"{name} & \\texttt{{{commit.split('$')[0]}}}{'$^{a}$' if '$' in commit else ''} & "
                    f"{thousands(n)} {unit} & {thousands(k)} & {p} & {valid} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print("wrote framework_table.tex")


if __name__ == "__main__":
    main()
