"""Manuscript guard: every macro used is defined, and no number is typed into prose.

Enforces PLAN rule 2 (no hand-typed numbers) against the TMLR draft. Numbers may appear only
through macros generated by scripts/fb_macros_aistats.py.

Run: python scripts/fb_check_manuscript.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MACROS = ROOT / "manuscript" / "tmlr" / "macros.tex"
DRAFT = ROOT / "manuscript" / "tmlr"
# LaTeX control sequences and environment names that are not macros of ours
LATEX = {"Section", "Sections", "Figure", "Table", "Appendix", "The", "A", "An", "In", "We",
         "This", "It", "If", "At", "Of", "On", "Every", "Because", "Human", "Three", "Two",
         "Nothing", "Once", "What", "First", "Second", "Finally", "Level", "Open", "LLM",
         "Leaderboard", "MATH", "Windows", "Unix", "February", "Great", "Kathy", "Final",
         "Math", "Verify", "TMLR",
         # standard LaTeX/math control sequences, not macros of ours
         "Delta", "Pr", "Consequently", "Suppose", "Stratifying", "Each", "Equation",
         "Tight", "Reporting", "Every", "Writing", "For", "Let", "Fix", "Under", "Because",
         "Exact", "Substituting", "Whenever", "Appendix", "Assumption", "Proposition",
         "Definition", "Section", "Table",
         # delimiter sizing used in the appendix proofs
         "Bigl", "Bigr"}
ALLOWED_DIGITS = {
    "2024", "2025",  # dated events (the leaderboard's own scoring eras)
    "400",           # the size of the pre-existing audit, fixed by its own preregistration
    "1",             # footnote marks
    "0",             # mathematical values such as eps = 0, not results
    "5",             # "Level-5", the benchmark's own subset name
    "22",            # verbatim quoted data in the opening example, reproduced from the response
    "000", "111",    # cell labels (verdict strings), not counts
    "101",           # the cell label used as a worked example in Section 2
    "0000", "1111",  # the four-verifier concordant cell labels (appendix)
    "0,1",           # the unit interval
    "2",             # exponents and pair subscripts in mathematics
    "1,0,1",         # the support of the paired difference D, from the appendix proofs
    "4",             # Hoeffding's Theorem 4, cited by number in the appendix proofs
    "2.0",           # "Apache 2.0", the release licence's version (DMLR data section)
}


STRUCTURAL = {"main.tex", "arxiv.tex", "dmlr.tex"}  # one per build: anonymous, arXiv, DMLR
SWITCH = {"SuppName", "SuppShort", "SuppWhere", "CodeURL"}  # body wording each build must define


def main():
    newcmd = r"\\newcommand\{\\(\w+)\}"
    defined = set(re.findall(newcmd, MACROS.read_text(encoding="utf-8")))
    problems = []
    for f in sorted(DRAFT.glob("*.tex")):
        if f.name in STRUCTURAL:
            own = set(re.findall(newcmd, f.read_text(encoding="utf-8")))
            problems += [f"{f.name}: build does not define \\{m}" for m in sorted(SWITCH - own)]
    defined |= SWITCH
    # build files are structural, not prose; every other exemption must declare itself generated
    # on its first line, so a new generated file cannot silently escape the number check.
    for f in sorted(DRAFT.glob("*.tex")):
        if f.name in STRUCTURAL:
            continue
        text = f.read_text(encoding="utf-8")
        if text.startswith("% Generated by scripts/"):
            continue
        body = re.sub(r"^%.*$", "", text, flags=re.M)
        for name in re.findall(r"\\([A-Za-z]+)", body):
            if name[0].isupper() and name not in defined and name not in LATEX:
                problems.append(f"{f.name}: undefined macro \\{name}")
        for num in re.findall(r"(?<![\w\\{])\d[\d,.]*", body):
            if num.rstrip(".,") not in ALLOWED_DIGITS:
                problems.append(f"{f.name}: hand-typed number {num!r} -- use a macro")
    for p in sorted(set(problems)):
        print("FAIL", p)
    print(f"{len(defined)} macros defined; {'OK' if not problems else str(len(set(problems))) + ' problem(s)'}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
