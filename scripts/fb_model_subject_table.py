"""Where the verifier disagreements fall: per model and per subject, computed without labels.

For every roster model and every MATH-Hard subject: accuracy under each of the four verifiers
(2024, boxed, Math-Verify, xFinder's primary arm), the share of responses that follow the
demonstrated template (the 2024 scorer's own extraction finds an answer), the share in a
discordant three-verifier cell, and, of those, the share whose disagreement is an extraction
failure (same decision tree as fb_extraction_taxonomy.classify). Per model it also gives the
model's rank under each verifier (1 = highest accuracy; ties share the best rank) and the
spread of those four ranks.

Run: python scripts/fb_model_subject_table.py
Out: results/analysis/model_subject_table.json, manuscript/tmlr/model_table.tex,
     manuscript/tmlr/subject_table.tex
"""
import gzip
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from flipbudget import verifiers as V  # noqa: E402
from fb_census_k3 import load_rows  # noqa: E402
from fb_extraction_taxonomy import classify  # noqa: E402

CENSUS = ROOT / "results" / "flipbudget" / "census_k3.json.gz"
XF = ROOT / "results" / "flipbudget" / "xfinder_verdicts.json.gz"
OUT = ROOT / "results" / "analysis" / "model_subject_table.json"
MODEL_TEX = ROOT / "manuscript" / "tmlr" / "model_table.tex"
SUBJECT_TEX = ROOT / "manuscript" / "tmlr" / "subject_table.tex"
VERIFIERS = ("em", "sb_sympy", "mv", "xf")
SUBJECT_NAMES = {"algebra": "algebra", "intermediate_algebra": "intermediate algebra",
                 "prealgebra": "prealgebra", "num_theory": "number theory", "precalculus": "precalculus",
                 "geometry": "geometry", "counting_and_prob": "counting and probability"}


def summarise(group):
    """group: list of row dicts carrying the four verdicts, 'tmpl' and 'cls'."""
    n = len(group)
    disc = [r for r in group if r["cls"] is not None]
    return {"n": n,
            "acc": {v: sum(int(r[v]) for r in group) / n for v in VERIFIERS},
            "template": sum(r["tmpl"] for r in group) / n,
            "discordant": len(disc),
            "discordant_extraction": sum(r["cls"].startswith("extraction") for r in disc)}


def ranks(acc_by_model, v):
    """Competition ranking, 1 = highest accuracy."""
    vals = {m: a["acc"][v] for m, a in acc_by_model.items()}
    return {m: 1 + sum(o > x for o in vals.values()) for m, x in vals.items()}


def pct(x):
    return f"{100 * x:.1f}"


def tex_name(m):
    return m.split("/", 1)[-1].replace("_", "\\_")


def write_model_tex(per_model, rank):
    order = sorted(per_model, key=lambda m: rank["em"][m])
    lines = ["% Generated by scripts/fb_model_subject_table.py -- do not edit by hand.",
             "\\begin{table}[t]", "\\centering", "\\footnotesize",
             "\\caption{Every roster model under each verifier, without human labels; all shares are percentages. "
             "Accuracy is the share of the model's responses credited; rank 1 is the highest accuracy among the "
             "roster, with ties sharing the best rank, and the spread is the largest minus the smallest of the four "
             "ranks. Template is the share of responses in which the 2024 verifier's extraction finds an answer; "
             "discordant is the share in a cell where the three verifiers disagree. Rows are in the order of the "
             "2024 verifier.}",
             "\\label{tab:models}", "\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{lrrrrcrrr}", "\\toprule",
             " & \\multicolumn{4}{c}{accuracy} & ranks & & & \\\\",
             "\\cmidrule(lr){2-5}",
             "model & 2024 & boxed & MV & xF & 2024/boxed/MV/xF & spread & template & discordant \\\\",
             "\\midrule"]
    for m in order:
        s = per_model[m]
        r = [rank[v][m] for v in VERIFIERS]
        lines.append(f"{tex_name(m)} & " + " & ".join(pct(s["acc"][v]) for v in VERIFIERS)
                     + f" & {'/'.join(map(str, r))} & {max(r) - min(r)} & {pct(s['template'])} & "
                     f"{pct(s['discordant'] / s['n'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    MODEL_TEX.write_text("\n".join(lines), encoding="utf-8")


def write_subject_tex(per_subject):
    order = sorted(per_subject, key=lambda s: -per_subject[s]["n"])
    lines = ["% Generated by scripts/fb_model_subject_table.py -- do not edit by hand.",
             "\\begin{table}[t]", "\\centering", "\\footnotesize",
             "\\caption{The seven MATH-Hard subjects, over all roster responses, without human labels; shares are "
             "percentages. Columns as in Table~\\ref{tab:models}; extraction is the share of the subject's "
             "discordant responses whose disagreement is a failure to extract an answer "
             "(Table~\\ref{tab:taxonomy}).}",
             "\\label{tab:subjects}", "\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{lrrrrrrrr}", "\\toprule",
             " & & \\multicolumn{4}{c}{accuracy} & & & \\\\", "\\cmidrule(lr){3-6}",
             "subject & responses & 2024 & boxed & MV & xF & template & discordant & extraction \\\\",
             "\\midrule"]
    for s in order:
        d = per_subject[s]
        n_fmt = f"{d['n']:,}".replace(",", "{,}")
        lines.append(f"{SUBJECT_NAMES[s]} & {n_fmt} & " + " & ".join(pct(d["acc"][v]) for v in VERIFIERS)
                     + f" & {pct(d['template'])} & {pct(d['discordant'] / d['n'])} & "
                     f"{pct(d['discordant_extraction'] / d['discordant'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    SUBJECT_TEX.write_text("\n".join(lines), encoding="utf-8")


def main():
    census = json.load(gzip.open(CENSUS, "rt", encoding="utf-8"))
    xf_all = json.load(gzip.open(XF, "rt", encoding="utf-8"))
    xf = xf_all["verdicts"][xf_all["primary_arm"]]
    text, _ = load_rows(census["models"])
    resp = {(t["model"], t["item_id"]): t["response"] for t in text}
    rows = []
    for r in census["rows"]:
        k = (r["model"], r["item_id"])
        tmpl = bool(isinstance(resp.get(k), str) and V.em_template_found(resp[k]))
        cell = "".join(str(int(r[f])) for f in ("em", "sb_sympy", "mv"))
        rows.append({**{f: int(r[f]) for f in ("em", "sb_sympy", "mv")}, "xf": int(xf[f"{k[0]}|{k[1]}"]["verdict"]),
                     "model": k[0], "subject": r["subject"], "tmpl": tmpl,
                     "cls": None if cell in ("000", "111") else classify(r, tmpl)})
    by_model, by_subject = defaultdict(list), defaultdict(list)
    for r in rows:
        by_model[r["model"]].append(r)
        by_subject[r["subject"]].append(r)
    per_model = {m: summarise(g) for m, g in by_model.items()}
    per_subject = {s: summarise(g) for s, g in by_subject.items()}
    rank = {v: ranks(per_model, v) for v in VERIFIERS}
    spread = {m: max(rank[v][m] for v in VERIFIERS) - min(rank[v][m] for v in VERIFIERS) for m in per_model}
    out = {"verifiers": VERIFIERS, "xfinder_arm": xf_all["primary_arm"], "per_model": per_model,
           "per_subject": per_subject, "ranks": rank, "rank_spread": spread,
           "summary": {"n_models": len(per_model), "n_responses": len(rows),
                       "rank_spread_median": statistics.median(spread.values()),
                       "rank_spread_max": max(spread.values()),
                       "models_rank_changes": sum(s > 0 for s in spread.values()),
                       "template_range_pct": [min(s["template"] for s in per_model.values()),
                                              max(s["template"] for s in per_model.values())],
                       "discordant_subject_range": [min(d["discordant"] / d["n"] for d in per_subject.values()),
                                                    max(d["discordant"] / d["n"] for d in per_subject.values())],
                       "extraction_share_subject_range": [
                           min(d["discordant_extraction"] / d["discordant"] for d in per_subject.values()),
                           max(d["discordant_extraction"] / d["discordant"] for d in per_subject.values())]}}
    json.dump(out, open(OUT, "w", encoding="utf-8"), indent=1)
    write_model_tex(per_model, rank)
    write_subject_tex(per_subject)
    print(json.dumps(out["summary"], indent=1))
    print("wrote", OUT, MODEL_TEX, SUBJECT_TEX)


if __name__ == "__main__":
    main()
