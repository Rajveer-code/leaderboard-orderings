"""T27 -- provenance table: every source the paper rests on, its version, a hash, and its check.

Hashes are computed here, at generation time, from the files in the repository (sha256, first
12 hex digits); the pinned upstream revisions are copied from the records that fetched them.

Run: python scripts/fb_provenance_table.py   Out: manuscript/tmlr/provenance_table.tex
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "flipbudget"
OUT = ROOT / "manuscript" / "tmlr" / "provenance_table.tex"


def h(path):
    return hashlib.sha256((ROOT / path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()[:12]


def brk(repo_id):
    """Let a long repository id break after its slash in a narrow column."""
    return repo_id.replace("/", "/\\allowbreak ")


def main():
    prov = json.load(open(RES / "verifier_provenance.json", encoding="utf-8"))
    s = prov["summary"]
    cfg = json.load(open(RES / "verifier_config.json", encoding="utf-8"))
    mv_match = sum(v["mv_matches_current_aggregate"] for m in prov["per_model"].values()
                   if m["results_original_revision"] for v in m["per_subject"].values())
    mv_cells = s["subjects"] - 7 * s["models_without_pre_rescoring_results"]
    shift = json.load(open(RES / "board_verifier_shift.json", encoding="utf-8"))["sources"]
    xf = json.load(__import__("gzip").open(RES / "xfinder_verdicts.json.gz", "rt", encoding="utf-8"))
    rows = [
        ("published responses", f"{s['models']} per-model result repositories, {s['subjects']} subject files; "
                                "revision of each file recorded in the release", "--",
         f"sample files unmodified since 2024 in {s['samples_never_modified_after_2024']} of {s['models']} models"),
        ("2024 verifier", "lm-evaluation-harness \\texttt{3c8db1bb7b}",
         h("provenance/verifier/lmeval_leaderboard_math_utils_3c8db1bb7b.py"),
         f"re-execution reproduces {s['items'] - s['items_em_vs_em_rec_disagree']:,} of {s['items']:,} "
         "published verdicts".replace(",", "{,}")),
        ("Math-Verify", f"math-verify {cfg['libraries']['math-verify']} via lm-evaluation-harness "
                        "\\texttt{61ee867816}", "--",
         f"reproduces the re-scored aggregate in {mv_match} of {mv_cells} model-subject combinations"),
        ("boxed verifier", "lm-evaluation-harness helpers, in the released code", h("vendor/leaderboard_math/utils.py"),
         "brute-force and printed-formula tests (Appendix~\\ref{app:tests})"),
        ("xFinder", "\\texttt{" + brk(xf["extractor"]) + "}", "--",
         "extractions judged by the equivalence routine"),
        ("scores before re-scoring", f"\\texttt{{{brk(shift['old']['repo'])}}} at \\texttt{{{shift['old']['revision'][:10]}}}",
         "--", "last revision before February 2025"),
        ("scores after re-scoring", f"\\texttt{{{brk(shift['new']['repo'])}}} at \\texttt{{{shift['new']['revision'][:10]}}}",
         "--", "final revision of the public table"),
        ("all verifier verdicts", "released verdict file", h("results/flipbudget/census_k3.json.gz"),
         "regenerated by the released pipeline"),
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_provenance_table.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{Provenance of every source the analysis rests on. "
                "Hashes are the first twelve hexadecimal digits of the sha256 of the file in the release, with "
                "line endings normalised; a dash marks an upstream artefact identified by its pinned version "
                f"instead. Verifier environment: sympy {cfg['libraries']['sympy']}, "
                f"latex2sympy2\\_extended {cfg['libraries']['latex2sympy2_extended']}.}}\n"
                "\\label{tab:provenance}\n\\small\n")
        f.write("\\begin{tabular}{p{0.16\\textwidth}p{0.3\\textwidth}lp{0.3\\textwidth}}\n\\toprule\n"
                "artefact & version & hash & check \\\\\n\\midrule\n")
        for name, version, hsh, check in rows:
            f.write(f"{name} & {version} & \\texttt{{{hsh}}} & {check} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
